                    ?: throw GradleException("storeFile غير موجود"))
                storePassword = keystoreProperties.getProperty("storePassword")
                    ?: throw GradleException("storePassword غير موجود")
            } else {
                throw GradleException("ملف key.properties غير موجود")
            }
        }
    }

