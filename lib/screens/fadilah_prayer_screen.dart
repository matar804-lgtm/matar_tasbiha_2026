      backgroundColor: const Color(0xFF0F2027),
      appBar: AppBar(
        backgroundColor: const Color(0xFF1B5E20),
        elevation: 0,
        title: const Text(
          'الصلاة الفاضلة على النبي ﷺ',
          style: TextStyle(
