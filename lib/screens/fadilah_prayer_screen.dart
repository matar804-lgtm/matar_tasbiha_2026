import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

class FadilahPrayerScreen extends StatelessWidget {
  const FadilahPrayerScreen({Key? key}) : super(key: key);

  // النص الكامل منسقاً وجاهزاً للعرض
  final String prayerText = """
بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ

اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْمُرْسَلِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْمُجَاهِدِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الشَّاهِدِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْخَائِفِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْخَاشِعِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الطَّائِعِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ التَّائِبِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْعَابِدِينَ.

اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْحَامِدِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الصَّالِحِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الرَّاكِعِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ السَّاجِدِينَ، اللَّهُمَّ صَلِّ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْقَائِمِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْقَاعِدِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْمُتَّقِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْمُسْتَغْفِرِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ النَّادِمِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الشَّاكِرِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْحَافِظِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الذَّاكِرِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْعَاقِلِينَ.

اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْمُحْسِنِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْأَكْرَمِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْمُنْذِرِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْمُبَشِّرِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الطَّيِّبِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ النَّبِيِّينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ الْعَالِمِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ النَّبِيِّ الزَّكِيِّ التَّقِيِّ النَّقِيِّ، اللَّهُمَّ صَلِّ وَسَلِّمْ وَبَارِكْ عَلَى سَيِّدِنَا مُحَمَّدٍ الْقُرَشِيِّ الْهَاشِمِيِّ، اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى سَيِّدِنَا مُحَمَّدٍ الْمَدَنِيِّ الْعَرَبِيِّ الْمُكَرَّمِ يَوْمَ الْقِيَامَةِ، اللَّهُمَّ صَلِّ وَسَلِّمْ وَبَارِكْ عَلَى سَيِّدِنَا مُحَمَّدٍ سَيِّدِ أَهْلِ الْجَنَّةِ، اللَّهُمَّ صَلِّ عَلَى سَيِّدِنَا مُحَمَّدٍ صَاحِبِ الْمَقَامِ الْمَحْمُودِ.

اللَّهُمَّ صَلِّ وَسَلِّمْ وَبَارِكْ عَلَى سَيِّدِنَا مُحَمَّدٍ صَاحِبِ الصِّرَاطِ الْمُسْتَقِيمِ، اللَّهُمَّ صَلِّ وَسَلِّمْ وَبَارِكْ عَلَى سَيِّدِنَا أَفْضَلِ الْأَوَّلِينَ وَالْآخِرِينَ، اللَّهُمَّ صَلِّ وَسَلِّمْ وَبَارِكْ عَلَى سَيِّدِنَا مُحَمَّدٍ وَعَلَى جَمِيعِ الْأَنْبِيَاءِ وَالْمُرْسَلِينَ، وَعَلَى جَمِيعِ الْمَلَائِكَةِ الْمُقَرَّبِينَ، وَعَلَى عِبَادِ اللَّهِ الصَّالِحِينَ مِنْ أَهْلِ السَّمَاوَاتِ وَأَهْلِ الْأَرَضِينَ، وَعَلَيْنَا مَعَهُمْ أَجْمَعِينَ بِرَحْمَتِكَ يَا أَرْحَمَ الرَّاحِمِينَ.

وَصَلَّى اللَّهُ عَلَى سَيِّدِنَا مُحَمَّدٍ وَعَلَى آلِهِ وَصَحْبِهِ وَسَلَّمَ أَجْمَعِينَ، وَسَلَّمَ تَسْلِيماً كَثِيراً.
""";

