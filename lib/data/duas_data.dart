class DuaItem {
  final String title;
  final String arabic;
  final String virtue; // فضل الدعاء
  final int repeatCount; // عدد التكرار المستحب
  final String source; // المصدر

  const DuaItem({
    required this.title,
    required this.arabic,
    required this.virtue,
    required this.repeatCount,
    required this.source,
  });
}

